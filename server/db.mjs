export async function ensureDefaultTypes(executor = pool) {
  const { rows } = await executor.query('SELECT COUNT(*) AS n FROM types');
  if (Number(rows[0].n) > 0) return;
  const stamp = nowIso();
  for (const type of DEFAULT_TYPES) {
    await executor.query(
      'INSERT INTO types (name, color, created_at) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING',
      [type.name, type.color, stamp],
    );
  }
}

const productSelect = `
  SELECT
    p.id, p.name, p.sku, p.type_id, p.unit, p.price, p.initial_stock,
    p.min_stock, p.expires_on, p.notes, p.created_at, p.updated_at,
    t.name AS type_name, t.color AS type_color,
    p.initial_stock + COALESCE((
      SELECT SUM(CASE WHEN m.kind = 'entrada' THEN m.quantity ELSE -m.quantity END)
      FROM movements m WHERE m.product_id = p.id
    ), 0) AS stock
  FROM products p
  JOIN types t ON t.id = p.type_id
`;

function mapProduct(row) {
  return {
    id: Number(row.id),
    name: row.name,
    sku: row.sku,
    typeId: Number(row.type_id),
    typeName: row.type_name,
    typeColor: row.type_color,
    unit: row.unit,
    price: Number(row.price),
    initialStock: Number(row.initial_stock),
    minStock: Number(row.min_stock),
    expiresOn: row.expires_on ?? null,
    notes: row.notes,
    stock: Number(row.stock),
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}

export async function listProducts(executor = pool) {
  const { rows } = await executor.query(`${productSelect} ORDER BY LOWER(p.name) ASC, p.id ASC`);
  return rows.map(mapProduct);
}

export async function getProductRow(id, executor = pool) {
  const { rows } = await executor.query(`${productSelect} WHERE p.id = $1`, [id]);
  return rows[0] ? mapProduct(rows[0]) : null;
}

export async function getProductStock(id, executor = pool) {
  const { rows } = await executor.query(`${productSelect} WHERE p.id = $1`, [id]);
  return rows[0] ? Number(rows[0].stock) : null;
}

export async function listTypes(executor = pool) {
  const { rows } = await executor.query(`
    WITH ps AS (
      SELECT p.id, p.type_id, p.price,
        p.initial_stock + COALESCE((
          SELECT SUM(CASE WHEN m.kind = 'entrada' THEN m.quantity ELSE -m.quantity END)
          FROM movements m WHERE m.product_id = p.id
        ), 0) AS stock
      FROM products p
    )
    SELECT t.id, t.name, t.color, t.created_at,
      COUNT(ps.id) AS product_count,
      COALESCE(SUM(ps.stock), 0) AS stock_total,
      COALESCE(SUM(ps.stock * ps.price), 0) AS stock_value
    FROM types t
    LEFT JOIN ps ON ps.type_id = t.id
    GROUP BY t.id, t.name, t.color, t.created_at
    ORDER BY LOWER(t.name) ASC
  `);
  return rows.map((row) => ({
    id: Number(row.id),
    name: row.name,
    color: row.color,
    productCount: Number(row.product_count),
    stockTotal: Number(row.stock_total),
    stockValue: Number(row.stock_value),
    createdAt: row.created_at,
  }));
}

function mapMovement(row) {
  return {
    id: Number(row.id),
    productId: Number(row.product_id),
    productName: row.product_name,
    productSku: row.product_sku,
    unit: row.unit,
    typeName: row.type_name ?? null,
    typeColor: row.type_color ?? null,
    kind: row.kind,
    quantity: Number(row.quantity),
    unitPrice: Number(row.unit_price),
    date: row.date,
    time: row.time,
    party: row.party,
    notes: row.notes,
    createdAt: row.created_at,
  };
}

const movementSelect = `
  SELECT m.*, p.name AS product_name, p.sku AS product_sku, p.unit AS unit,
    t.name AS type_name, t.color AS type_color
  FROM movements m
  JOIN products p ON p.id = m.product_id
  JOIN types t ON t.id = p.type_id
`;

export async function getMovementById(id, executor = pool) {
  const { rows } = await executor.query(`${movementSelect} WHERE m.id = $1`, [id]);
  return rows[0] ? mapMovement(rows[0]) : null;
}

export async function listMovements({ days = 0, limit = 500 } = {}) {
  const params = [];
  let where = '';
  if (days > 0) {
    where = 'WHERE m.date >= $1';
    params.push(addDays(todayStr(), -(days - 1)));
  }
  const safeLimit = Math.min(Math.max(Number(limit) || 500, 1), 2000);
  params.push(safeLimit);
  const { rows } = await pool.query(
    `${movementSelect} ${where} ORDER BY m.date DESC, m.time DESC, m.id DESC LIMIT $${params.length}`,
    params,
  );
  return rows.map(mapMovement);
}

async function periodTotals(from, to) {
  const row = await one(
    `
    SELECT
      COALESCE(SUM(CASE WHEN kind = 'saida' THEN quantity ELSE 0 END), 0) AS saida_qty,
      COALESCE(SUM(CASE WHEN kind = 'saida' THEN quantity * unit_price ELSE 0 END), 0) AS saida_value,
      COALESCE(SUM(CASE WHEN kind = 'entrada' THEN quantity ELSE 0 END), 0) AS entrada_qty,
      COALESCE(SUM(CASE WHEN kind = 'entrada' THEN quantity * unit_price ELSE 0 END), 0) AS entrada_value,
      COUNT(*) AS movements
    FROM movements
    WHERE date BETWEEN $1 AND $2
  `,
    [from, to],
  );
  return {
    saidaQty: Number(row.saida_qty),
    saidaValue: Number(row.saida_value),
    entradaQty: Number(row.entrada_qty),
    entradaValue: Number(row.entrada_value),
    movements: Number(row.movements),
  };
}

export async function getAnalytics(days = 30) {
  const safeDays = [7, 30, 90, 365].includes(Number(days)) ? Number(days) : 30;
  const today = todayStr();
  const from = addDays(today, -(safeDays - 1));
  const prevTo = addDays(from, -1);
  const prevFrom = addDays(prevTo, -(safeDays - 1));

  const [
    products,
    totals,
    previous,
    todayTotals,
    dailyResult,
    byTypeResult,
    topProductsResult,
    topPartiesResult,
    heatResult,
    idleResult,
    lastSalesResult,
    recentResult,
  ] = await Promise.all([
    listProducts(),
    periodTotals(from, today),
    periodTotals(prevFrom, prevTo),
    periodTotals(today, today),
    pool.query(
      `
      SELECT date,
        COALESCE(SUM(CASE WHEN kind = 'saida' THEN quantity ELSE 0 END), 0) AS saida_qty,
        COALESCE(SUM(CASE WHEN kind = 'saida' THEN quantity * unit_price ELSE 0 END), 0) AS saida_value,
        COALESCE(SUM(CASE WHEN kind = 'entrada' THEN quantity ELSE 0 END), 0) AS entrada_qty,
        COALESCE(SUM(CASE WHEN kind = 'entrada' THEN quantity * unit_price ELSE 0 END), 0) AS entrada_value,
        COUNT(*) AS movements
      FROM movements
      WHERE date BETWEEN $1 AND $2
      GROUP BY date
    `,
      [from, today],
    ),
    pool.query(
      `
      SELECT t.id, t.name, t.color,
        COALESCE(SUM(m.quantity), 0) AS qty,
        COALESCE(SUM(m.quantity * m.unit_price), 0) AS value,
        COUNT(m.id) AS n
      FROM movements m
      JOIN products p ON p.id = m.product_id
      JOIN types t ON t.id = p.type_id
      WHERE m.kind = 'saida' AND m.date BETWEEN $1 AND $2
      GROUP BY t.id, t.name, t.color
      ORDER BY qty DESC
    `,
      [from, today],
    ),
    pool.query(
      `
      SELECT p.id, p.name, p.sku, p.unit, t.name AS type_name, t.color AS type_color,
        COALESCE(SUM(m.quantity), 0) AS qty,
        COALESCE(SUM(m.quantity * m.unit_price), 0) AS value
      FROM movements m
      JOIN products p ON p.id = m.product_id
      JOIN types t ON t.id = p.type_id
      WHERE m.kind = 'saida' AND m.date BETWEEN $1 AND $2
      GROUP BY p.id, p.name, p.sku, p.unit, t.name, t.color
      ORDER BY qty DESC, value DESC
      LIMIT 6
    `,
      [from, today],
    ),
    pool.query(
      `
      SELECT MIN(party) AS party, COALESCE(SUM(quantity), 0) AS qty, COUNT(*) AS n
      FROM movements
      WHERE kind = 'saida' AND date BETWEEN $1 AND $2 AND TRIM(party) <> ''
      GROUP BY LOWER(TRIM(party))
      ORDER BY qty DESC
      LIMIT 4
    `,
      [from, today],
    ),
    pool.query(
      `
      SELECT
        EXTRACT(DOW FROM date::date)::int AS weekday,
        CAST(substr(time, 1, 2) AS INTEGER) AS hour,
        COALESCE(SUM(quantity), 0) AS qty,
        COUNT(*) AS n
      FROM movements
      WHERE kind = 'saida' AND date BETWEEN $1 AND $2
      GROUP BY weekday, hour
    `,
      [from, today],
    ),
    pool.query(
      `
      ${productSelect}
      WHERE NOT EXISTS (
        SELECT 1 FROM movements m
        WHERE m.product_id = p.id AND m.kind = 'saida' AND m.date BETWEEN $1 AND $2
      )
      ORDER BY (p.initial_stock * p.price) DESC
      LIMIT 12
    `,
      [from, today],
    ),
    pool.query(`
      SELECT product_id, MAX(date) AS last_date, MAX(time) AS last_time
      FROM movements WHERE kind = 'saida'
      GROUP BY product_id
    `),
    pool.query(`${movementSelect} ORDER BY m.date DESC, m.time DESC, m.id DESC LIMIT 8`),
  ]);

  const stockQty = products.reduce((sum, p) => sum + Math.max(p.stock, 0), 0);
  const stockValue = products.reduce((sum, p) => sum + Math.max(p.stock, 0) * p.price, 0);
  const inventoryValue = products.reduce((sum, p) => sum + p.initialStock * p.price, 0);

  const lowStock = products
    .filter((p) => p.stock <= p.minStock)
    .sort((a, b) => a.stock - b.stock)
    .map((p) => ({ ...p }));
  const expiring = products
    .filter(
      (p) => p.expiresOn && p.stock > 0 && p.expiresOn >= today && p.expiresOn <= addDays(today, 30),
    )
    .sort((a, b) => String(a.expiresOn).localeCompare(String(b.expiresOn)))
    .map((p) => ({ ...p }));
  const outOfStock = products.filter((p) => p.stock <= 0);
  const expired = products
    .filter((p) => p.expiresOn && p.stock > 0 && p.expiresOn < today)
    .sort((a, b) => String(a.expiresOn).localeCompare(String(b.expiresOn)))
    .map((p) => ({ ...p }));

  const dailyMap = new Map();
  for (const row of dailyResult.rows) {
    dailyMap.set(row.date, row);
  }
  const daily = [];
  for (let cursor = from; ; cursor = addDays(cursor, 1)) {
    const row = dailyMap.get(cursor);
    daily.push({
      date: cursor,
      saidaQty: Number(row?.saida_qty ?? 0),
      saidaValue: Number(row?.saida_value ?? 0),
      entradaQty: Number(row?.entrada_qty ?? 0),
      entradaValue: Number(row?.entrada_value ?? 0),
      movements: Number(row?.movements ?? 0),
    });
    if (cursor === today) break;
  }

  const byType = byTypeResult.rows.map((row) => ({
    id: Number(row.id),
    name: row.name,
    color: row.color,
    qty: Number(row.qty),
    value: Number(row.value),
    count: Number(row.n),
  }));

  const topProducts = topProductsResult.rows.map((row) => ({
    id: Number(row.id),
    name: row.name,
    sku: row.sku,
    unit: row.unit,
    typeName: row.type_name,
    typeColor: row.type_color,
    qty: Number(row.qty),
    value: Number(row.value),
  }));

  const topParties = topPartiesResult.rows.map((row) => ({
    party: row.party,
    qty: Number(row.qty),
    count: Number(row.n),
  }));

  const heatmap = [];
  for (let weekday = 0; weekday < 7; weekday += 1) {
    for (let bucket = 0; bucket < 4; bucket += 1) {
      heatmap.push({ weekday, bucket, qty: 0, count: 0 });
    }
  }
  const weekdayTotals = [0, 0, 0, 0, 0, 0, 0];
  const bucketTotals = [0, 0, 0, 0];
  for (const row of heatResult.rows) {
    const weekday = Number(row.weekday);
    const bucket = Math.min(3, Math.floor(Number(row.hour) / 6));
    const cell = heatmap[weekday * 4 + bucket];
    cell.qty += Number(row.qty);
    cell.count += Number(row.n);
    weekdayTotals[weekday] += Number(row.qty);
    bucketTotals[bucket] += Number(row.qty);
  }

  const idleRows = idleResult.rows.map(mapProduct);
  const lastSaleMap = new Map(
    lastSalesResult.rows.map((row) => [
      Number(row.product_id),
      `${row.last_date} ${row.last_time}`,
    ]),
  );

  const byTypeStockMap = new Map();
  for (const p of products) {
    const current = byTypeStockMap.get(p.typeId) ?? {
      id: p.typeId,
      name: p.typeName,
      color: p.typeColor,
      qty: 0,
      value: 0,
      products: 0,
    };
    current.qty += Math.max(p.stock, 0);
    current.value += Math.max(p.stock, 0) * p.price;
    current.products += 1;
    byTypeStockMap.set(p.typeId, current);
  }

  const recent = recentResult.rows.map(mapMovement);
  const uniqueAttention = new Set([...lowStock, ...expiring, ...expired].map((p) => p.id));

  return {
    period: {
      days: safeDays,
      from,
      to: today,
      prevFrom,
      prevTo,
    },
    totals: {
      ...totals,
      previous,
      todaySaidaQty: todayTotals.saidaQty,
      todaySaidaValue: todayTotals.saidaValue,
      todayMovements: todayTotals.movements,
    },
    stock: {
      productCount: products.length,
      stockQty,
      stockValue,
      initialValue: inventoryValue,
      lowStockCount: lowStock.length,
      expiringCount: expiring.length,
      outOfStockCount: outOfStock.length,
      expiredCount: expired.length,
      attentionCount: uniqueAttention.size,
    },
    attention: {
      lowStock: lowStock.slice(0, 8),
      expiring: expiring.slice(0, 8),
      expired: expired.slice(0, 8),
    },
    daily,
    byType,
    topProducts,
    topParties,
    heatmap,
    weekdayTotals,
    bucketTotals,
    idleProducts: idleRows.map((p) => ({
      ...p,
      lastSale: lastSaleMap.get(p.id) ?? null,
    })),
    byTypeStock: Array.from(byTypeStockMap.values()).sort((a, b) => b.value - a.value),
    recent,
  };
}

export function generateSku(name, existingSkus = new Set()) {
  const cleaned = String(name)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '')
    .slice(0, 3);
  const prefix = cleaned.length >= 2 ? cleaned.padEnd(3, 'X') : 'PRD';
  for (let attempt = 0; attempt < 40; attempt += 1) {
    const digits = String(Math.floor(1000 + Math.random() * 9000));
    const sku = `${prefix}-${digits}`;
    if (!existingSkus.has(sku)) return sku;
  }
  return `PRD-${Date.now().toString().slice(-7)}`;
}

export async function allSkus() {
  const { rows } = await pool.query('SELECT sku FROM products');
  return new Set(rows.map((row) => row.sku));
}

export async function resetData() {
  await transaction(async (client) => {
    await client.query('TRUNCATE TABLE movements, products, types RESTART IDENTITY CASCADE');
    await client.query("DELETE FROM meta WHERE key LIKE 'demo%'");
  });
}

export async function exportAll() {
  const [types, products, movementRows, admin] = await Promise.all([
    listTypes(),
    listProducts(),
    pool.query(`${movementSelect} ORDER BY m.date ASC, m.time ASC, m.id ASC`),
    getAdmin(),
  ]);
  return {
    app: 'Controles da Silmara',
    version: 1,
    exportedAt: nowIso(),
    admin: admin ? { name: admin.name, createdAt: admin.created_at } : null,
    types,
    products,
    movements: movementRows.rows.map(mapMovement),
  };
}
