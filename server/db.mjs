import pg from 'pg';

const { Pool } = pg;

if (!process.env.DATABASE_URL) {
  try {
    process.loadEnvFile();
  } catch {
    // Em produção as variáveis vêm do ambiente da Vercel.
  }
}

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  throw new Error('DATABASE_URL não configurada. Defina a conexão do Postgres/Supabase no .env.');
}

const localDatabase = /(^|@)(localhost|127\.0\.0\.1)(:|\/|$)/.test(connectionString);

export const pool = new Pool({
  connectionString,
  ssl: localDatabase || process.env.PGSSL === 'disable' ? false : { rejectUnauthorized: false },
  max: Number(process.env.PG_POOL_MAX) || (process.env.VERCEL ? 3 : 5),
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 12_000,
  allowExitOnIdle: true,
  application_name: 'controles-da-silmara',
});

pool.on('error', (error) => {
  console.error('Erro no pool do Postgres:', error.message);
});

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS admin (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    recovery_hash TEXT,
    created_at TEXT NOT NULL,
    password_changed_at TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    last_seen TEXT NOT NULL,
    user_agent TEXT,
    ip_hash TEXT
  );

  CREATE TABLE IF NOT EXISTS auth_throttle (
    key TEXT PRIMARY KEY,
    failures INTEGER NOT NULL DEFAULT 0,
    locked_until TEXT,
    updated_at TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    color TEXT NOT NULL,
    created_at TEXT NOT NULL
  );

  CREATE UNIQUE INDEX IF NOT EXISTS idx_types_name_lower ON types (LOWER(name));

  CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    sku TEXT NOT NULL UNIQUE,
    type_id INTEGER NOT NULL REFERENCES types(id) ON DELETE RESTRICT,
    unit TEXT NOT NULL DEFAULT 'un',
    price DOUBLE PRECISION NOT NULL DEFAULT 0,
    initial_stock DOUBLE PRECISION NOT NULL DEFAULT 0,
    min_stock DOUBLE PRECISION NOT NULL DEFAULT 0,
    expires_on TEXT,
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
  );

  CREATE TABLE IF NOT EXISTS movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('entrada', 'saida')),
    quantity DOUBLE PRECISION NOT NULL CHECK (quantity > 0),
    unit_price DOUBLE PRECISION NOT NULL DEFAULT 0,
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    party TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL
  );

  CREATE INDEX IF NOT EXISTS idx_movements_date ON movements(date);
  CREATE INDEX IF NOT EXISTS idx_movements_product ON movements(product_id);
  CREATE INDEX IF NOT EXISTS idx_movements_kind_date ON movements(kind, date);
`;

let initPromise = null;

export function initDb() {
  if (!initPromise) {
    initPromise = pool.query(SCHEMA).catch((error) => {
      initPromise = null;
      throw error;
    });
  }
  return initPromise;
}

export async function one(text, params = []) {
  const { rows } = await pool.query(text, params);
  return rows[0] ?? null;
}

export async function many(text, params = []) {
  const { rows } = await pool.query(text, params);
  return rows;
}

export async function transaction(fn) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    try {
      await client.query('ROLLBACK');
    } catch {
      // A conexão já pode ter sido encerrada pelo pooler.
    }
    throw error;
  } finally {
    client.release();
  }
}

export function nowIso() {
  return new Date().toISOString();
}

export function todayStr(d = new Date()) {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

export function addDays(dateStr, amount) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const dt = new Date(y, m - 1, d + amount);
  return todayStr(dt);
}

export async function getMeta(key, executor = pool) {
  const { rows } = await executor.query('SELECT value FROM meta WHERE key = $1', [key]);
  return rows[0] ? rows[0].value : null;
}

export async function setMeta(key, value, executor = pool) {
  await executor.query(
    'INSERT INTO meta (key, value) VALUES ($1, $2) ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value',
    [key, String(value)],
  );
}

export async function deleteMeta(key) {
  await pool.query('DELETE FROM meta WHERE key = $1', [key]);
}

export async function isConfigured() {
  const row = await one('SELECT 1 AS present FROM admin WHERE id = 1');
  return Boolean(row);
}

export async function getAdmin() {
  return one('SELECT * FROM admin WHERE id = 1');
}

